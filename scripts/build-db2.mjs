import {build} from '../frontend/node_modules/esbuild/lib/main.js';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {contractManifest, digest} from '../server/validate.js';
const paths = [
  'frontend/src/features/transposable-elements/engine',
];
import {readdir} from 'node:fs/promises';
const engineFiles = (await readdir(paths[0])).filter(p => p.endsWith('.js')).sort();
const engine = createHash('sha256');
for (const p of engineFiles) engine.update(p).update(await readFile(`${paths[0]}/${p}`));
const manifest = {...contractManifest, engine_sha256: engine.digest('hex')};
const hash = await digest(manifest);
await mkdir('supabase/functions/learner-write', {recursive: true});
await build({entryPoints: ['server/handler.js'], outfile: 'supabase/functions/learner-write/handler.generated.js', bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', banner: {js: '// Generated by npm run build:db2. Do not edit.'}});
await writeFile('supabase/contract-manifest.json', JSON.stringify({...manifest, sha256: hash}, null, 2) + '\n');
await writeFile('supabase/seed.sql', `-- Generated contract registry; no learner records.\ninsert into private.contract_manifests (version, fingerprint, engine_sha256) values ('siaset-v1', '${await digest(contractManifest)}', '${manifest.engine_sha256}') on conflict do nothing;\n`);
console.log(`Generated trusted validator and pinned contract ${hash}`);
